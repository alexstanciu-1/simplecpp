header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store, no-cache, must-revalidate, max-age=0');
header('Pragma: no-cache');
header('Expires: 0');

ob_start();

$__jsonResponseSent = false;

function emitJsonResponse(array $payload, int $statusCode = 200): void
{
	global $__jsonResponseSent;
	$bufferedOutput = ob_get_contents();
	while (ob_get_level() > 0) {
		@ob_end_clean();
	}
	$__jsonResponseSent = true;
	if ($bufferedOutput !== false && $bufferedOutput !== '') {
		if (!isset($payload['error']) || $payload['error'] === '') {
			$payload['error'] = 'Unexpected output before JSON response: ' . trim((string) $bufferedOutput);
		}
	}
	http_response_code($statusCode);
	echo json_encode($payload, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
	exit;
}

$response = [
	'ok' => false,
	'error' => '',
	'generator_header_display' => '',
	'generator_source_display' => '',
	'generator_error' => '',
	's2s_generator_output' => '',
	'generator_include_directive' => '',
	'php_output' => '',
	'php_error' => '',
	'php_exit_code' => null,
	'cpp_output' => '',
	'cpp_error' => '',
	'cpp_exit_code' => null,
	'cpp_compile_output' => '',
	'cpp_compile_error' => '',
	'cpp_compile_exit_code' => null,
	'php_ast_json' => '',
	'php_ast_source' => 'php-ast-json',
	'timing_resources' => [],
	'timing_resources_json' => '',
	'debug_json' => '',
];

register_shutdown_function(static function () use (&$response, &$__jsonResponseSent): void {
	if ($__jsonResponseSent) {
		return;
	}

	$lastError = error_get_last();
	$bufferedOutput = ob_get_contents();
	while (ob_get_level() > 0) {
		@ob_end_clean();
	}

	if ($lastError === null && ($bufferedOutput === false || $bufferedOutput === '')) {
		return;
	}

	if ($lastError !== null) {
		$response['error'] = 'Fatal shutdown: ' . ($lastError['message'] ?? 'unknown error');
		$response['generator_error'] = $response['error'];
		$response['generator_header_display'] = $response['error'];
		$response['generator_source_display'] = '';
		http_response_code(500);
	} elseif ($bufferedOutput !== false && trim((string) $bufferedOutput) !== '') {
		$response['error'] = 'Unexpected non-JSON output before shutdown: ' . trim((string) $bufferedOutput);
		$response['generator_error'] = $response['error'];
		$response['generator_header_display'] = $response['error'];
		$response['generator_source_display'] = '';
		http_response_code(500);
	} else {
		$response['error'] = 'Empty JSON response body generated by run.php.';
		http_response_code(500);
	}

	if (!isset($response['timing_resources_json']) || $response['timing_resources_json'] === '') {
		$response['timing_resources_json'] = encodePrettyJson($response['timing_resources'] ?? []);
	}
	if (!isset($response['debug_json']) || $response['debug_json'] === '') {
		$response['debug_json'] = buildDebugJson($response, '', $response['php_ast_json'] ?? '');
	}

	echo json_encode($response, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
});

try {
	$action = (string) ($_GET['action'] ?? '');
	if ($action !== '') {
		handleUtilityAction($action);
		return;
	}

	if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
		throw new RuntimeException('POST required.');
	}

	$data = readJsonRequestBody();

	$phpCode = trim((string) ($data['php_code'] ?? ''));
	$memTestEnabled = (bool) ($data['mem_test_enabled'] ?? false);
	if ($phpCode === '') {
		throw new RuntimeException('PHP code is empty.');
	}

	if (!str_starts_with(ltrim($phpCode), '<?php')) {
		$phpCode = "<?php\n" . $phpCode;
	}

	if (!extension_loaded('ast')) {
		throw new RuntimeException('The php-ast extension is required for this test UI.');
	}

	$repoRoot = realpath(__DIR__ . '/../../');
	if ($repoRoot === false) {
		throw new RuntimeException('Project root not found.');
	}

	require_once $repoRoot . '/bin/bootstrap.php';
	require_once $repoRoot . '/bin/project_services.php';

	$sandboxRoot = getSandboxRootPath();
	ensureSandboxRootExists($sandboxRoot);
	$selectedSandboxPath = (string) ($data['selected_sandbox_path'] ?? '');
	$entrypointRelativePath = resolveUiEntrypointRelativePath($sandboxRoot, $selectedSandboxPath);
	$entrypointAbsolutePath = resolveSandboxPathInsideRoot($sandboxRoot, $entrypointRelativePath, false);
	ensureDirectoryExists(dirname($entrypointAbsolutePath));
	if (file_put_contents($entrypointAbsolutePath, $phpCode) === false) {
		throw new RuntimeException('Failed to save sandbox entrypoint: ' . $entrypointRelativePath);
	}

	$timingResources = [];
	$response['project_root'] = $sandboxRoot;
	$response['project_entrypoint'] = $entrypointRelativePath;

	$projectConfig = find_project_config($sandboxRoot);
	if ($projectConfig === null) {
		$initStage = measureStage(static function () use ($sandboxRoot, $repoRoot): array {
			return runScppCliService($repoRoot, $sandboxRoot, ['init']);
		});
		$initResult = $initStage['result'];
		$timingResources['init_project'] = stageMetricsFromMeasured($initStage, 'scpp init');
		$timingResources['init_project']['exit_code'] = $initResult['exit_code'];
		$timingResources['init_project']['command'] = $initResult['command'];
		$response['project_init_output'] = normalizeCommandOutput((string) $initResult['output']);
		$response['project_init_error'] = trim((string) $initResult['error']);
		if (!$initResult['ok']) {
			throw new RuntimeException(trim((string) $initResult['error']));
		}
		$projectConfig = find_project_config($sandboxRoot);
	}
	if ($projectConfig === null) {
		throw new RuntimeException('Failed to resolve sandbox project config after initialization.');
	}
	$buildConfigPath = prepareUiBuildConfigPath($projectConfig['project_root'], $projectConfig['config_path'], $entrypointRelativePath);
	if ($buildConfigPath !== $projectConfig['config_path']) {
		$overrideConfigJson = file_get_contents($buildConfigPath);
		if (!is_string($overrideConfigJson) || $overrideConfigJson === '') {
			throw new RuntimeException('Failed to read temporary UI build config.');
		}
		if (file_put_contents($projectConfig['config_path'], $overrideConfigJson) === false) {
			throw new RuntimeException('Failed to refresh sandbox prism.json for selected entrypoint.');
		}
		$buildConfigPath = $projectConfig['config_path'];
	}
	$buildConfig = load_project_config($buildConfigPath);
	$timingResources['project_config'] = [
		'label' => 'Project config',
		'config_path' => normalizeConfigPathForUi(relative_path($projectConfig['project_root'], $buildConfigPath)),
		'entrypoint' => normalizeConfigPathForUi((string) ($buildConfig['entrypoint'] ?? 'main.php')),
	];

	$phpPath = $entrypointAbsolutePath;

	$astVersion = max(ast\get_supported_versions());
	$astStage = measureStage(static function () use ($phpCode, $astVersion): array {
		$fixture = [
			'php_version' => PHP_VERSION,
			'php_ast_extension_version' => phpversion('ast'),
			'ast_version_used' => $astVersion,
			'supported_versions' => ast\get_supported_versions(),
			'tokens' => \token_get_all($phpCode),
			'ast' => ast\parse_code($phpCode, $astVersion),
		];

		return [
			'fixture' => $fixture,
			'json' => (string) json_encode($fixture, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR),
		];
	});
	$phpAstJson = $astStage['result']['json'];
	file_put_contents($phpPath . '.json', $phpAstJson);
	$response['php_ast_json'] = $phpAstJson;
	$timingResources['parse_ast'] = stageMetricsFromMeasured($astStage, 'PHP AST parse + tokens');

	$generatorStage = measureStage(static function () use ($phpPath): array {
		$transpiler = new Transpiler();
		$cppFile = $transpiler->transpile($phpPath);
		return ['cpp_file' => $cppFile];
	});
	$cppFile = $generatorStage['result']['cpp_file'];
	$timingResources['create_cpp_code'] = stageMetricsFromMeasured($generatorStage, 'S2S generate C++');

	$headerDisplay = implode("\n", $cppFile->headerLines) . "\n";
	$sourceDisplay = implode("\n", normalizeSourceForUi($cppFile->sourceLines)) . "\n";
	$response['generator_include_directive'] = extractIncludeDirective($sourceDisplay, $headerDisplay);

	$generatorErrors = implode("\n", $cppFile->errors);
	$generatorWarnings = implode("\n", $cppFile->warnings);
	$response['generator_error'] = $generatorErrors;
	$response['s2s_generator_output'] = $generatorWarnings;
	$response['generator_header_display'] = $generatorErrors !== '' ? $generatorErrors : $headerDisplay;
	$response['generator_source_display'] = $generatorErrors !== '' ? '' : $sourceDisplay;

	$phpRun = runCommandMeasured(
		['php', __DIR__."/run_include.php", $phpPath],
		$repoRoot,
		20
	);
	$response['php_output'] = normalizeCommandOutput($phpRun['stdout']);
	$response['php_error'] = buildProcessErrorText('PHP execution', $phpRun);
	$response['php_exit_code'] = $phpRun['exit_code'];
	$timingResources['execute_php'] = externalMetricsFromRun('PHP execute', $phpRun);

	if ($generatorErrors !== '') {
		$response['cpp_compile_output'] = '';
		$response['cpp_compile_error'] = '';
