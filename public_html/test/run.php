function cleanupDirectory(string $path): void
{
	if (!is_dir($path)) {
		return;
	}

	$items = scandir($path);
	if ($items === false) {
		return;
	}

	foreach ($items as $item) {
		if ($item === '.' || $item === '..') {
			continue;
		}
		$child = $path . '/' . $item;
		if (is_dir($child)) {
			cleanupDirectory($child);
			continue;
		}
		@unlink($child);
	}

	@rmdir($path);
}

