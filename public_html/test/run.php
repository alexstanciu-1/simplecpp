			return ensureRuntimeArchive($projectRoot, $memTestEnabled);
		});
		$runtimeArchive = (string) $runtimeCacheStage['result']['archive_path'];
		$runtimeCacheMetrics = stageMetricsFromMeasured($runtimeCacheStage, 'C++ runtime cache');
		$runtimeCacheMetrics['cache_status'] = (string) ($runtimeCacheStage['result']['status'] ?? 'unknown');
		$runtimeCacheMetrics['archive_path'] = $runtimeArchive;
		$runtimeCacheMetrics['mode'] = $memTestEnabled ? 'asan' : 'default';
		$response['timing_resources']['compile_cpp_runtime_cache'] = $runtimeCacheMetrics;

		$compileInputPath = $tempRoot . '/snippet.build.cpp';
		file_put_contents($compileInputPath, buildNaturalCompileUnitFromText($headerText, $sourceText));
		$cppBinaryPath = $tempRoot . '/snippet.out';

		$compileRun = runCommandMeasured(
			buildSampleCompileCommand($projectRoot, $compileInputPath, $runtimeArchive, $cppBinaryPath, $memTestEnabled),
			$tempRoot,
			40
		);
		$response['cpp_compile_output'] = normalizeCommandOutput($compileRun['stdout']);
		$response['cpp_compile_error'] = buildProcessErrorText('C++ compile', $compileRun);
		$response['cpp_compile_exit_code'] = $compileRun['exit_code'];
		$compileMetrics = externalMetricsFromRun('C++ compile', $compileRun);
		$compileMetrics['mode'] = $memTestEnabled ? 'edited_cpp_plus_cached_runtime_archive_asan' : 'edited_cpp_plus_cached_runtime_archive';
		$compileMetrics['mem_test_enabled'] = $memTestEnabled;
		$response['timing_resources']['compile_cpp'] = $compileMetrics;

		if ($compileRun['exit_code'] !== 0) {
			$response['cpp_error'] = $response['cpp_compile_error'];
			$response['timing_resources']['execute_cpp'] = [
				'label' => 'C++ execute',
				'skipped' => true,
				'reason' => 'compile_failed',
			];
		} else {
			$cppRun = runCommandMeasured([$cppBinaryPath], $tempRoot, 20);
			$response['cpp_output'] = normalizeCommandOutput($cppRun['stdout']);
			$response['cpp_error'] = buildProcessErrorText('C++ execution', $cppRun);
			$response['cpp_exit_code'] = $cppRun['exit_code'];
			$response['timing_resources']['execute_cpp'] = externalMetricsFromRun('C++ execute', $cppRun);
		}

		$response['timing_resources_json'] = encodePrettyJson($response['timing_resources']);
		$response['debug_json'] = encodePrettyJson([
			'mode' => 'compile_edited_cpp',
			'mem_test_enabled' => $memTestEnabled,
			'cpp_compile_exit_code' => $response['cpp_compile_exit_code'],
			'cpp_exit_code' => $response['cpp_exit_code'],
			'cpp_compile_error' => $response['cpp_compile_error'],
			'cpp_error' => $response['cpp_error'],
			's2s_generator_output' => '',
			'generator_error' => '',
			'timing_resources' => $response['timing_resources'],
		]);
		$response['ok'] = true;
		return $response;
	} finally {
		}
}

function encodePrettyJson(array $data): string
{
	return (string) json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
}

function formatThrowableDetails(Throwable $throwable): string
{
	$parts = [];
	$parts[] = $throwable->getMessage();
	$parts[] = 'File: ' . $throwable->getFile();
	$parts[] = 'Line: ' . $throwable->getLine();
	$parts[] = "Trace:\n" . $throwable->getTraceAsString();

	return implode("\n", $parts);
}

function buildEffectivePath(?string $pathEnv = null): string
{
	$pathEnv = is_string($pathEnv) ? trim($pathEnv) : '';
	$dirs = [];
	if ($pathEnv !== '') {
		$dirs = array_filter(explode(PATH_SEPARATOR, $pathEnv), static fn (string $dir): bool => $dir !== '');
	}
	if (DIRECTORY_SEPARATOR !== '\\') {
		$dirs = array_merge($dirs, [
			'/usr/local/sbin',
			'/usr/local/bin',
			'/usr/sbin',
			'/usr/bin',
			'/sbin',
			'/bin',
			'/usr/games',
			'/usr/local/games',
			'/snap/bin',
		]);
	}
	$normalized = [];
	foreach ($dirs as $dir) {
		$dir = trim($dir);
		if ($dir === '') {
			continue;
		}
		$normalized[] = rtrim($dir, "\/");
	}
	$normalized = array_values(array_unique($normalized));
	return implode(PATH_SEPARATOR, $normalized);
}

function buildProcessEnvironment(array $extra = []): array
{
	$env = [];
	foreach ([getenv(), $_ENV, $_SERVER] as $source) {
		if (!is_array($source)) {
			continue;
		}
		foreach ($source as $key => $value) {
			if (!is_string($key) || $key == '') {
				continue;
			}
			if (is_array($value) || is_object($value) || $value === null) {
				continue;
			}
			$env[$key] = (string) $value;
		}
	}
	foreach ($extra as $key => $value) {
		if (!is_string($key) || $key == '') {
			continue;
		}
		if (is_array($value) || is_object($value) || $value === null) {
			continue;
		}
		$env[$key] = (string) $value;
	}
	$env['PATH'] = buildEffectivePath($env['PATH'] ?? null);
	return $env;
}

function commandExistsOnPath(string $command): bool
{
	$pathEnv = buildEffectivePath(getenv('PATH') === false ? null : (string) getenv('PATH'));
	if ($pathEnv === '') {
		return false;
	}

	$dirs = array_filter(explode(PATH_SEPARATOR, $pathEnv), static fn (string $dir): bool => $dir !== '');
	$extensions = [''];
	if (DIRECTORY_SEPARATOR === '\\') {
		$pathext = getenv('PATHEXT');
		$extensions = $pathext === false || $pathext === ''
			? ['.exe', '.cmd', '.bat', '.com', '']
			: array_merge(explode(';', strtolower((string) $pathext)), ['']);
		$extensions = array_values(array_unique($extensions));
	}

	foreach ($dirs as $dir) {
		$dir = rtrim($dir, "\\/");
		foreach ($extensions as $extension) {
			$candidate = $dir . DIRECTORY_SEPARATOR . $command;
			if ($extension !== '' && !str_ends_with(strtolower($candidate), $extension)) {
				$candidate .= $extension;
			}
			if (is_file($candidate)) {
				return true;
			}
		}
	}

	return false;
}

function withCompilerLauncher(array $command): array
{
	if ($command === [] || !compilerLauncherIsUsable('sccache', (string) $command[0])) {
		return $command;
	}

	array_unshift($command, 'sccache');
	return $command;
}

function compilerLauncherIsUsable(string $launcher, string $compiler): bool
{
	if ($compiler === '' || !commandExistsOnPath($launcher)) {
		return false;
	}

	$descriptor = [
		0 => ['pipe', 'r'],
		1 => ['pipe', 'w'],
		2 => ['pipe', 'w'],
	];
	$process = @proc_open([$launcher, $compiler, '--version'], $descriptor, $pipes, null, buildProcessEnvironment());
	if (!is_resource($process)) {
		return false;
	}

	fclose($pipes[0]);
	stream_get_contents($pipes[1]);
	stream_get_contents($pipes[2]);
	fclose($pipes[1]);
	fclose($pipes[2]);
	$status = proc_close($process);
	return is_int($status) && $status === 0;
}

function buildRuntimeCompileCommand(string $projectRoot, string $sourcePath, string $objectPath, bool $memTestEnabled = false): array
{
	$mysqliConfig = getRuntimeUiMysqliPkgConfig($projectRoot);
	$command = [
		'g++',
		'-std=c++23',
		'-O3',
		'-DSCPP_LANGUAGE_TARGET_PHP=1',
		'-DSCPP_HAS_MYSQLI=' . ($mysqliConfig['enabled'] ? '1' : '0'),
	];

	if ($memTestEnabled) {
		$command[] = '-fsanitize=address';
	}

	$command = array_merge($command, [
		'-c',
		$sourcePath,
		'-I',
		$projectRoot . '/runtime/include',
	], $mysqliConfig['cflags'], [
		'-o',
		$objectPath,
	]);

	return withCompilerLauncher($command);
}

function buildSampleCompileCommand(string $projectRoot, string $compileInputPath, string $runtimeArchive, string $cppBinaryPath, bool $memTestEnabled = false): array
{
	$mysqliConfig = getRuntimeUiMysqliPkgConfig($projectRoot);
	$command = [
		'g++',
		'-std=c++23',
		'-O3',
		'-DSCPP_LANGUAGE_TARGET_PHP=1',
		'-DSCPP_HAS_MYSQLI=' . ($mysqliConfig['enabled'] ? '1' : '0'),
	];

	if ($memTestEnabled) {
		$command[] = '-fsanitize=address';
	}

	$command = array_merge($command, [
		$compileInputPath,
		$runtimeArchive,
		'-I',
		$projectRoot . '/runtime/include',
	]);

	if (!$memTestEnabled) {
		$command[] = '-ljemalloc';
	}

	$command = array_merge($command, $mysqliConfig['libs'], [
		'-o',
		$cppBinaryPath,
	]);

	return withCompilerLauncher($command);
}
