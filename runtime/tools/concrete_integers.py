"""Generate concrete integer declarations and adapters to existing runtime semantics."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = json.loads((ROOT / 'specs/config.json').read_text())['runtime']['concrete_integer_api']
INTEGERS = CONFIG['types']


def generate():
    banner = '// Generated by runtime/tools/concrete_integers.py; edit the generator.\n'
    header = [banner, '#pragma once\n\nnamespace scpp\n{\n', '''	class boolean final
	{
	public:
		constexpr boolean() noexcept = default;
		constexpr boolean(bool value) noexcept : value_(value) {}
		explicit constexpr operator bool() const noexcept { return this->value_; }
		constexpr bool native_value() const noexcept { return this->value_; }
		boolean operator!() const noexcept;
	private:
		bool value_ = false;
	};

''']
    source = [banner, '#include "scpp/integers.hpp"\n#include "scpp/generated/operators.hpp"\n'
              '#include "operators/isset/isset.hpp"\n\nnamespace scpp\n{\n',
              '\tboolean boolean::operator!() const noexcept\n\t{\n'
              '\t\treturn (!bool_t(this->native_value())).native_value();\n\t}\n\n']
    header.extend(f'\tclass {name};\n' for name, _ in INTEGERS)
    for name, rep in INTEGERS:
        native = f'int_t<{rep}>'
        header.extend([f'\n\tclass {name} final\n\t{{\n\tpublic:\n',
                       f'\t\tconstexpr {name}() noexcept = default;\n',
                       f'\t\tconstexpr {name}({rep} value) noexcept : value_(value) {{}}\n',
                       f'\t\texplicit {name}(boolean value) noexcept;\n',
                       f'\t\tconstexpr {rep} native_value() const noexcept {{ return this->value_; }}\n'])
        source.append(f'\t{name}::{name}(boolean value) noexcept : value_({native}(static_cast<int>(static_cast<bool>(value))).native_value()) {{}}\n')
        for other, _ in INTEGERS:
            if other != name:
                header.append(f'\t\texplicit {name}({other} value) noexcept;\n')
                source.append(f'\t{name}::{name}({other} value) noexcept : value_({native}(value.native_value()).native_value()) {{}}\n')
        for op in ('++', '--'):
            header.append(f'\t\t{name} &operator{op}() noexcept;\n')
            source.append(f'\t{name} &{name}::operator{op}() noexcept\n\t{{\n'
                          f'\t\tauto value = {native}(this->value_);\n\t\t{op}value;\n'
                          '\t\tthis->value_ = value.native_value();\n\t\treturn *this;\n\t}\n\n')
        for op in ('+', '-', '*', '/', '%'):
            header.append(f'\t\t{name} &operator{op}=({name} right);\n')
            source.append(f'\t{name} &{name}::operator{op}=({name} right)\n\t{{\n'
                          f'\t\t*this = *this {op} right;\n\t\treturn *this;\n\t}}\n\n')
        header.append(f'\tprivate:\n\t\t{rep} value_ = 0;\n\t}};\n\n')
        for op in ('+', '-', '*', '/', '%', '==', '!=', '<', '<=', '>', '>='):
            result = name if op in ('+', '-', '*', '/', '%') else 'boolean'
            header.append(f'\t{result} operator{op}({name} left, {name} right);\n')
            source.append(f'\t{result} operator{op}({name} left, {name} right)\n\t{{\n'
                          f'\t\treturn ({native}(left.native_value()) {op} {native}(right.native_value())).native_value();\n\t}}\n\n')
        header.append(f'\tboolean isset({name} value);\n')
        source.append(f'\tboolean isset({name} value)\n\t{{\n'
                      f'\t\treturn scpp::isset({native}(value.native_value())).native_value();\n\t}}\n\n'
                      f'\tstatic_assert(sizeof({name}) == sizeof({native}));\n'
                      f'\tstatic_assert(alignof({name}) == alignof({native}));\n\n')
    header.append('\tboolean isset(boolean value);\n}\n')
    source.append('\tboolean isset(boolean value)\n\t{\n'
                  '\t\treturn scpp::isset(bool_t(value.native_value())).native_value();\n\t}\n}\n')
    keys = [banner, '#pragma once\n#include "scpp/integers.hpp"\n#include "scpp/hash_t.hpp"\nnamespace scpp::hash_detail\n{\n']
    for name, rep in INTEGERS:
        keys.append(f'''	template<> struct integer_key_policy<scpp::{name}> final
	{{ using rep = {rep}; }};
	template<> struct key_ops<scpp::{name}> final
	{{
		static std::uint64_t hash(const scpp::{name} &key)
		{{ return key_ops<int_t<{rep}>>::hash(int_t<{rep}>(key.native_value())); }}
		static bool equal(const scpp::{name} &left, const scpp::{name} &right)
		{{ return key_ops<int_t<{rep}>>::equal(int_t<{rep}>(left.native_value()), int_t<{rep}>(right.native_value())); }}
	}};
''')
    keys.append('}\n')
    return {ROOT / 'include/scpp/detail/concrete_integer_keys.hpp': ''.join(keys),
            ROOT / 'public'  / CONFIG['header']: ''.join(header),
            ROOT / 'include/core/integers.cpp': ''.join(source)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale concrete integer output: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
