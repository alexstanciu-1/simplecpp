#!/usr/bin/env python3
"""Probe the target ABI for inline public values; run with the runtime compiler/flags.

Generated output is published with the runtime, never selected by its consumers.
Cross compilation requires a target runner; unsupported here rather than guessing.
"""
import argparse
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--compiler', default='clang++')
parser.add_argument('--flag', action='append', default=[])
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
types = [('STRING', 'scpp::string_t'), ('ERROR_VALUE', 'scpp::error_t'),
         ('EXCEPTION_INFO', 'std::exception_ptr')]
source = '#include "scpp/error_t.hpp"\n#include <cstdio>\n#include <exception>\n#include <type_traits>\nint main() {\n'
for name, native in types:
    for trait in ('move_constructible', 'move_assignable', 'destructible'):
        source += f'static_assert(std::is_nothrow_{trait}_v<{native}>);\n'
    if name == 'EXCEPTION_INFO':
        source += 'static_assert(std::is_nothrow_copy_constructible_v<std::exception_ptr>);\n'
        source += 'static_assert(std::is_nothrow_copy_assignable_v<std::exception_ptr>);\n'
    source += f'std::printf("%zu %zu\\n", sizeof({native}), alignof({native}));\n'
source += '}\n'
with tempfile.TemporaryDirectory(prefix='scpp-value-layout-') as directory:
    executable = str(Path(directory) / 'probe')
    subprocess.run([args.compiler, '-std=c++23', *args.flag, '-I'+str(root/'include'),
                    '-x', 'c++', '-', '-o', executable], input=source, text=True, check=True)
    layouts = subprocess.check_output([executable], text=True).splitlines()
output = '// Generated by runtime/tools/value_layout.py for the runtime target ABI.\n'
output += '// Regenerate for a different ABI; implementation assertions reject stale layouts.\n#pragma once\n'
for (name, native), layout in zip(types, layouts, strict=True):
    size, alignment = map(int, layout.split())
    output += f'#define SCPP_{name}_SIZE {size}\n#define SCPP_{name}_ALIGNMENT {alignment}\n'
    print(f'{name}: size={size}, alignment={alignment}; lifecycle traits verified')
path = root/'public/scpp/detail/value_layout.hpp'
if args.check:
    if not path.exists() or path.read_text() != output:
        raise SystemExit('Stale runtime value layout; regenerate with the target compiler and flags')
else:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(output)
