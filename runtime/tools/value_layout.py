#!/usr/bin/env python3
"""Probe the target ABI for inline public values; run with the runtime compiler/flags.

Generated output is published with the runtime, never selected by its consumers.
Cross compilation requires a target runner; unsupported here rather than guessing.
"""
import argparse
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--compiler', default='clang++')
parser.add_argument('--flag', action='append', default=[])
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = '''#include "scpp/string_t.hpp"
#include <cstdio>
#include <type_traits>
int main() {
    static_assert(std::is_nothrow_move_constructible_v<scpp::string_t>);
    static_assert(std::is_nothrow_move_assignable_v<scpp::string_t>);
    static_assert(std::is_nothrow_destructible_v<scpp::string_t>);
    std::printf("%zu %zu\\n", sizeof(scpp::string_t), alignof(scpp::string_t));
}
'''
with tempfile.TemporaryDirectory(prefix='scpp-value-layout-') as directory:
    executable = str(Path(directory) / 'probe')
    subprocess.run([args.compiler, '-std=c++23', *args.flag, '-I'+str(root/'include'),
                    '-x', 'c++', '-', '-o', executable], input=source, text=True, check=True)
    size, alignment = map(int, subprocess.check_output([executable], text=True).split())
output = f'''// Generated by runtime/tools/value_layout.py for the runtime target ABI.
// Regenerate for a different ABI; implementation assertions reject stale layouts.
#pragma once
#define SCPP_STRING_SIZE {size}
#define SCPP_STRING_ALIGNMENT {alignment}
'''
path = root/'public/scpp/detail/value_layout.hpp'
if args.check:
    if not path.exists() or path.read_text() != output:
        raise SystemExit('Stale runtime value layout; regenerate with the target compiler and flags')
else:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(output)
print(f'string: size={size}, alignment={alignment}; nonthrowing move/assignment/destruction verified')
