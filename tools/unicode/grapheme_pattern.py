"""Build the private Unicode 14 extended-grapheme pattern from the two official UCD files."""
import hashlib
from pathlib import Path
import sys

properties = {}
for path, digest in zip(map(Path, sys.argv[1:]), (
    '97e79f1f8d9cd76d120f2420381a01abc00a7c78a2aa583fa3f9627264a99742',
    'b597836124298b8f7fa076273802840cfc3271a25f5c397a082e120954b82c3c',
), strict=True):
    if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
        raise ValueError(f"Unexpected Unicode 14 property file: {path}")
    for line in path.read_text().splitlines():
        entry = line.partition('#')[0].strip()
        if entry:
            span, prop = map(str.strip, entry.split(';'))
            bounds = [int(n, 16) for n in span.split('..')]
            properties.setdefault(prop, []).append((bounds[0], bounds[-1]))

def chars(*names, negate=False):
    merged = []
    for start, end in sorted(r for n in names for r in properties[n]):
        if merged and start == merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], end)
        else:
            merged.append((start, end))
    def literal(n):
        return rf'\x{{{n:x}}}'
    return ('[^' if negate else '[') + ''.join(
        literal(a) if a == b else literal(a) + '-' + literal(b) for a, b in merged) + ']'

# UAX #29 GB3–GB5: a control ends the cluster, with CRLF as one unit.
control = chars('CR', 'LF', 'Control')
base = chars('CR', 'LF', 'Control', negate=True)
# GB6–GB8: maximal Hangul sequence. The separate L and T alternatives
# include runs with no medial vowel and runs starting with a trailing Jamo.
l, v, t, lv, lvt = map(chars, ('L', 'V', 'T', 'LV', 'LVT'))
hangul = f'{l}*+(?:{v}++|{lv}{v}*+|{lvt}){t}*+|{l}++|{t}++'
# GB11: return capture 1 at a confirmed pictographic join. The caller
# continues the same cluster, keeping PCRE stack use independent of chain length.
pic = chars('Extended_Pictographic')
join = f"({pic}{chars('Extend')}*+{chars('ZWJ')}(?={pic}))"
# GB12/13 pair flags. GB9/9a consume the suffix and GB9b consumes prepends.
pair = chars('Regional_Indicator') + '{1,2}+'
suffix = chars('Extend', 'ZWJ', 'SpacingMark') + '*+'
prepend = chars('Prepend') + '*+'
# After prepends, a control or end can terminate the cluster without a base.
pattern = rf'\r\n|{control}|{prepend}(?:{join}|(?:{hangul}|{pair}|{base}|(?={control}|\z)){suffix})'
print('// Generated by tools/unicode/grapheme_pattern.py from Unicode 14.0.0.')
print('// Unicode data license: tools/unicode/LICENSE.txt')
for i in range(0, len(pattern), 120):
    print('R"ucd(' + pattern[i:i+120] + ')ucd"')
