#!/usr/bin/env python3
"""Run existing representation/adapter witnesses against the minimal layout.

Prerequisite: existing proof source fixtures generated by the provider-policy
verification tools. Changes only include paths/declarations, preserves witnesses.
"""
import argparse,json,re,subprocess
from pathlib import Path
from experiment import require_scratch,write_changed
from minimal_type_layout import INCLUDE,identifiers
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--app',type=Path,required=True);p.add_argument('--out',type=Path,required=True);a=p.parse_args();app=a.app.resolve();require_scratch(app);a.out.mkdir(parents=True,exist_ok=True)
build=app/'.prism/build';gen=app/'.prism/minimal/generated';manifest=json.loads((build/'latency-minimal-manifest.json').read_text());names=set(manifest['types'])
graph=(build/'latency-minimal.ninja').read_text();link=re.search(r'^build minimal-main: link (.+)$',graph,re.M);objects=[x for x in link[1].split() if x!='minimal_parts/main.o'];assert len(objects)==len(link[1].split())-1
graph=graph.replace('default minimal-main','');targets=[]
for label in ['value-proof','carrier-proof','composition-proof','adapter-semantics']:
    original=(build/(label+'.cpp')).read_text();body=INCLUDE.sub('',original);used=identifiers(body)&names
    retained=[]
    for inc in INCLUDE.findall(original):
        if inc.startswith('__callable/'):
            retained.append(inc);used|=identifiers((gen/inc).read_text())&names
    text=''.join('#include "__types/'+n+'.hpp"\n' for n in sorted(used))+''.join('#include "'+inc+'"\n' for inc in retained)+body
    target='minimal-'+label;write_changed(build/(target+'.cpp'),text);write_changed(a.out/(target+'.cpp'),text)
    graph+='\nbuild '+target+'.o: compile '+target+'.cpp | expanded_runtime_pch.hpp.gch\nbuild '+target+': link '+target+'.o '+' '.join(objects)+'\n';targets.append(target)
graph+='\ndefault '+' '.join(targets)+'\n';write_changed(build/'minimal-proofs.ninja',graph)
r=subprocess.run(['ninja','-f','minimal-proofs.ninja','-j12'],cwd=build,text=True,capture_output=True);(a.out/'build.log').write_text(r.stdout+r.stderr);r.check_returncode()
for target in targets:
    r=subprocess.run([str(build/target)],cwd=app,text=True,capture_output=True);(a.out/(target+'.log')).write_text(r.stdout+r.stderr);r.check_returncode()
print('value copies, shared carriers, composition identity/output and adapters passed')
