#!/usr/bin/env python3
"""Extend the existing callable model to frontend and partition the LLVM owner.

All final artifacts and objects are independent of the earlier layout. Intermediate
mirrors are regenerated by the same bounded emitters; no native class definitions
from different layouts are linked together.
"""
import re
from pathlib import Path
from callable_surface import prepare as callables, TARGETS
from partitioned_callables import prepare as partitions, SOURCES
from layout_isolation import prepare as isolate_row
from experiment import require_scratch,write_changed

TARGETS_EXPANDED = {**TARGETS,'frontend_model_builder':'compile/frontend_adapter/phs/frontend_model_builder'}
SOURCES_EXPANDED = [*SOURCES,'compile/backend/llvm_text_from_plan']
PUBLICATION_CONSUMERS = [
    'compile/backend/backend_object_link_cache',
    'compile/backend/lowering_plan',
    'compile/capabilities/storage_lifetime_readiness',
    'compile/capabilities/type_capability_readiness',
    'compile/incremental/resident_source_unit_symbol_states',
    'compile/model/project_reference_resolution',
]

def prepare(app, partition_consumers=False, isolate_tables=False, isolate_counters=False, uniform_helpers=False, isolate_adapters=False, isolate_composition_type=False):
    require_scratch(app)
    if isolate_composition_type and not (isolate_adapters and isolate_counters):
        raise ValueError("Composition type candidate requires adapter and counter staging")
    targets = dict(TARGETS_EXPANDED)
    if isolate_tables:
        targets['frontend_model_tables'] = 'structure_kernel/frontend_model_tables'
    rejected = []
    if isolate_adapters:
        from adapter_catalog import audit
        adapter_audit = audit(app / '.prism/generated')
        if adapter_audit['rejected']:
            raise ValueError('Unrecognized adapter surfaces: ' + str(adapter_audit['rejected']))
    if uniform_helpers or isolate_adapters:
        from callable_surface import catalog
        targets, rejected = catalog(app, include_adapters=isolate_adapters)
    callables(app,targets=targets,include_adapters=isolate_adapters)
    if uniform_helpers or isolate_adapters:
        from callable_groups import prepare as group_callables
        group_callables(app, targets)
    partition_sources = SOURCES_EXPANDED + (PUBLICATION_CONSUMERS if partition_consumers else [])
    # Sources wholly owned by extracted helpers no longer have a residual object.
    graph = (app / '.prism/build/latency-callables.ninja').read_text()
    partition_sources = [source for source in partition_sources if 'build callables/' + source + '.o: compile ' in graph]
    partitions(app,sources=partition_sources)
    isolate_row(app)
    src=app/'.prism/layout/generated';dst=app/'.prism/expanded/generated';build=app/'.prism/build'
    graph=(build/'latency-layout.ninja').read_text()
    if isolate_counters:
        # Transform in staging; publish each final byte sequence only once so
        # narrowing includes never creates false timestamp invalidation.
        stage=app/'.prism/counter-staging/generated'
        for path in src.rglob('*'):
            if path.is_file() and path.suffix in ['.hpp','.cpp']:
                write_changed(stage/path.relative_to(src),path.read_text())
        from counter_boundary import prepare as counter_boundary
        graph=counter_boundary(app,stage,graph).replace(str(stage),str(dst))
        publish=stage
    else:
        publish=src
    type_publication = None
    if isolate_composition_type:
        from private_composition_type import prepare as publish_type
        type_publication = publish_type(app, publish, graph)
    for path in publish.rglob('*'):
        if path.is_file() and path.suffix in ['.hpp','.cpp']:
            write_changed(dst/path.relative_to(publish),path.read_text())
    graph=graph.replace(str(src),str(dst)).replace('../layout/generated','../expanded/generated')
    graph=graph.replace('layout-project.pch','expanded-project.pch').replace('layout_runtime_pch.hpp','expanded_runtime_pch.hpp')
    graph=re.sub(r'(?<!\S)layout_parts/','expanded_parts/',graph)
    graph=re.sub(r'(?<!\S)layout/','expanded/',graph)
    write_changed(build/'expanded_runtime_pch.hpp',(build/'app_pch.hpp').read_text())
    write_changed(build/'latency-expanded.ninja',graph)
    import json
    write_changed(build/'latency-expanded-manifest.json',json.dumps({'callable_owners':targets,'partition_owners':partition_sources,'uniform_helpers':uniform_helpers,'isolate_adapters':isolate_adapters,'rejected_class_surfaces':rejected,'counter_boundary':isolate_counters,'composition_type_publication':type_publication,'native_class_definitions':'identical between partition-consumer modes; added callable owners change declarations and require dependency-driven rebuild'},indent=2)+'\n')

if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser()
    p.add_argument('--app',type=Path,required=True)
    p.add_argument('--partition-consumers',action='store_true')
    p.add_argument('--isolate-tables',action='store_true')
    p.add_argument('--isolate-counters',action='store_true')
    p.add_argument('--uniform-helpers',action='store_true')
    p.add_argument('--isolate-adapters',action='store_true')
    p.add_argument('--isolate-composition-type',action='store_true')
    a=p.parse_args()
    prepare(a.app.resolve(),partition_consumers=a.partition_consumers,
            isolate_tables=a.isolate_tables,isolate_counters=a.isolate_counters,uniform_helpers=a.uniform_helpers,isolate_adapters=a.isolate_adapters,isolate_composition_type=a.isolate_composition_type)
