"""Prelower the registry's scalar facades; generated public headers contain no templates."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    mappings = json.loads((ROOT / "types.json").read_text())["mappings"]
    integers = [m for m in mappings if "scalar_rep" in m]
    banner = "// Generated by middleware/tools/scalar_types.py; edit the generator.\n"
    header = [banner, "#pragma once\n\nnamespace scpp::compiler_support\n{\n",
              "\tstruct scalar_access;\n\n\tclass boolean final\n\t{\n\tpublic:\n",
              "\t\tboolean() noexcept;\n\t\tboolean(bool value) noexcept;\n",
              "\t\texplicit operator bool() const noexcept;\n\t\tboolean operator!() const noexcept;\n",
              "\n\tprivate:\n\t\tfriend struct scalar_access;\n\t\tbool value_;\n\t};\n\n"]
    access = [banner, '#pragma once\n#include "scpp_compiler/types.hpp"\n#include "runtime_scalars.hpp"\n\n',
              'namespace scpp::compiler_support\n{\n\tstruct scalar_access\n\t{\n',
              '\t\tstatic bindings::native_boolean get(boolean value) noexcept\n\t\t{\n\t\t\treturn bindings::native_boolean(value.value_);\n\t\t}\n']
    source = [banner, '#include "scalar_access.hpp"\n#include "scpp/generated/operators.hpp"\n#include "operators/isset/isset.hpp"\n\n',
              'namespace scpp::compiler_support\n{\n',
              '\tboolean::boolean() noexcept : value_(bindings::native_boolean().native_value())\n\t{\n\t}\n\n',
              '\tboolean::boolean(bool value) noexcept : value_(bindings::native_boolean(value).native_value())\n\t{\n\t}\n\n',
              '\tboolean::operator bool() const noexcept\n\t{\n\t\treturn static_cast<bool>(scalar_access::get(*this));\n\t}\n\n',
              '\tboolean boolean::operator!() const noexcept\n\t{\n\t\treturn (!scalar_access::get(*this)).native_value();\n\t}\n\n']
    header.extend(f'\tclass {m["name"]};\n' for m in integers)
    header.append('\n')
    for m in integers:
        n, rep = m['name'], m['scalar_rep']
        header += [f'\tclass {n} final\n\t{{\n\tpublic:\n',
                   f'\t\t{n}() noexcept;\n\t\t{n}({rep} value) noexcept;\n',
                   f'\t\texplicit {n}(boolean value) noexcept;\n',
                   f'\t\t{n} &operator++() noexcept;\n\t\t{n} &operator--() noexcept;\n']
        for other in integers:
            if other['name'] != n:
                header.append(f'\t\texplicit {n}({other["name"]} value) noexcept;\n')
                source.append(f'\t{n}::{n}({other["name"]} value) noexcept : value_(bindings::native_{n}(scalar_access::get(value).native_value()).native_value())\n\t{{\n\t}}\n\n')
        for op in ['+','-','*','/','%']:header.append(f'\t\t{n} &operator{op}=({n} right);\n')
        header += [f'\n\tprivate:\n\t\tfriend struct scalar_access;\n\t\t{rep} value_;\n\t}};\n\n']
        access.append(f'\n\t\tstatic bindings::native_{n} get({n} value) noexcept\n\t\t{{\n\t\t\treturn bindings::native_{n}(value.value_);\n\t\t}}\n')
        source += [f'\t{n}::{n}() noexcept : value_(bindings::native_{n}().native_value())\n\t{{\n\t}}\n\n',
                   f'\t{n}::{n}({rep} value) noexcept : value_(bindings::native_{n}(value).native_value())\n\t{{\n\t}}\n\n',
                   f'\t{n}::{n}(boolean value) noexcept : value_(bindings::native_{n}(static_cast<int>(static_cast<bool>(value))).native_value())\n\t{{\n\t}}\n\n']
        for op in ['++','--']:
            source.append(f'\t{n} &{n}::operator{op}() noexcept\n\t{{\n\t\tauto value = scalar_access::get(*this);\n\t\t{op}value;\n\t\tthis->value_ = value.native_value();\n\t\treturn *this;\n\t}}\n\n')
        for op in ['+','-','*','/','%','==','!=','<','<=','>','>=']:
            result = n if op in ['+','-','*','/','%'] else 'boolean'
            header.append(f'\t{result} operator{op}({n} left, {n} right);\n')
            source.append(f'\t{result} operator{op}({n} left, {n} right)\n\t{{\n\t\treturn (scalar_access::get(left) {op} scalar_access::get(right)).native_value();\n\t}}\n\n')
        for op in ['+','-','*','/','%']:
            source.append(f'\t{n} &{n}::operator{op}=({n} right)\n\t{{\n\t\t*this = *this {op} right;\n\t\treturn *this;\n\t}}\n\n')
        header.append(f'\tboolean isset({n} value);\n\n')
        source.append(f'\tboolean isset({n} value)\n\t{{\n\t\treturn scpp::isset(scalar_access::get(value)).native_value();\n\t}}\n\n')
        source.append(f'\tstatic_assert(sizeof({n}) == sizeof(bindings::native_{n}));\n\tstatic_assert(alignof({n}) == alignof(bindings::native_{n}));\n\n')
    header += ['\tboolean isset(boolean value);\n}\n\nnamespace scpp::compiler\n{\n']
    for name in ['boolean']+[m['name'] for m in integers]+['isset']:
        header.append(f'\tusing compiler_support::{name};\n')
    header.append('}\n')
    access.append('\t};\n}\n')
    source.append('\tboolean isset(boolean value)\n\t{\n\t\treturn scpp::isset(scalar_access::get(value)).native_value();\n\t}\n}\n')
    return {ROOT/'include/scpp_compiler/types.hpp': ''.join(header),
            ROOT/'src/scalar_access.hpp': ''.join(access), ROOT/'src/types.cpp': ''.join(source)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Stale generated scalar facade: {path}')
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
