"""Re-export runtime-owned concrete scalars and generate their private template adapters."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    mappings = json.loads((ROOT / 'types.json').read_text())['mappings']
    scalars = [m for m in mappings if m.get('bridge') == 'scalars']
    banner = '// Generated by middleware/tools/scalar_types.py; edit the generator.\n'
    header = [banner, '#pragma once\n']
    header.extend(f'#include "{name}"\n' for name in sorted({m['public_runtime_header'] for m in scalars}))
    header.append('\nnamespace scpp::compiler_support\n{\n')
    header.extend(f'\tusing {m["public_runtime"]};\n' for m in scalars)
    header.append('\tusing scpp::isset;\n}\n\nnamespace scpp::compiler\n{\n')
    header.extend(f'\tusing compiler_support::{m["name"]};\n' for m in scalars)
    header.append('\tusing compiler_support::isset;\n}\n')
    access = [banner, '#pragma once\n#include "scpp_compiler/types.hpp"\n#include "runtime_scalars.hpp"\n\n',
              'namespace scpp::compiler_support\n{\n\tstruct scalar_access\n\t{\n']
    for m in scalars:
        name = m['name']
        access.append(f'\t\tstatic bindings::native_{name} get({name} value) noexcept\n\t\t{{\n'
                      f'\t\t\treturn bindings::native_{name}(value.native_value());\n\t\t}}\n\n')
    access.append('\t};\n}\n')
    return {ROOT / 'include/scpp_compiler/types.hpp': ''.join(header),
            ROOT / 'src/scalar_access.hpp': ''.join(access)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Stale scalar re-export: {path}')
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
