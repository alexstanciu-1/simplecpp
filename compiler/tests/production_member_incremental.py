"""Exercise production member dependencies through a resident project and a persistent Ninja graph."""
import json
from pathlib import Path
import sys
import tempfile

from app_namespace_native import artifacts, invoke, service
from extends_native import source_edit
from inline_adapters_native import incremental_native_build


def properties():
    node = 'class Node {public int $x=3; public function __construct(){}}'
    sources = {
        'node': node,
        'reader': 'function readX(Node $n):int {return (int)$n->x;}',
        'writer': 'function writeX(Node $n,Node $other):void {$n->x=$other->x;}',
        'maker': 'function makeNode():Node {return new Node();}',
        'control': 'class Other {public int $x=5;} function quiet(Other $n):int{return $n->x;}',
        'main': '$n=makeNode(); echo readX($n); writeX($n,new Node()); echo readX($n),quiet(new Other()); return 8;',
    }
    return sources, [(None, '', b'335'), ('node', node.replace('int $x', 'byte $x'), b'335'),
                     ('node', node.replace('public int $x=3;', ''), 'Unknown field Node.x'), ('node', node, b'335')]


def methods():
    base = 'class Base {public virtual function value(int $n=1):int{return $n;}}'
    derived = 'class Child extends Base {public override function value(int $n=1):int{return 10+$n;}}'
    sources = {
        'base': base, 'child': derived,
        'reader': 'function readBase(Base $n):int{return $n->value();}',
        'control': 'class Other {public function value():int{return 5;}} function quiet(Other $n):int{return $n->value();}',
        'main': '$n=new Child(); echo readBase($n),$n->value(),quiet(new Other());return 8;',
    }
    return sources, [(None, '', b'11115'), ('child', derived.replace('10+', '20+'), b'21215'),
                     ('child', derived.replace('int $n', 'float $n'), 'signature'),
                     ('child', 'class Child extends Base {}', b'115'), ('child', derived, b'11115')]


def constants():
    left = 'struct Left {public const int LIMIT=2;}'
    right = left.replace('Left', 'Right').replace('2', '3')
    read = 'function readLimit():int{return Left::LIMIT;}'
    sources = {'left': left, 'right': right, 'reader': read,
               'control': 'struct Other {public const int LIMIT=5;} function quiet():int{return Other::LIMIT;}',
               'main': 'echo readLimit(),quiet();return 8;'}
    return sources, [(None, '', b'25'), ('reader', read.replace('Left', 'Right'), b'35'),
                     ('left', left.replace('2', '4'), b'35'), ('right', right.replace('3', '7'), b'75'),
                     ('right', 'struct Right {}', 'LIMIT'), ('right', right, b'35')]


def construction():
    base = 'class Base {public int $x=1; public function __construct(int $v=2){$this->x+=$v;}}'
    sources = {'base': base, 'child': 'class Child extends Base {}',
               'omitted': 'function omitted():int {$n=new Child();return $n->x;}',
               'explicit': 'function supplied():int {$n=new Child(8);return $n->x;}',
               'control': 'class Other {public int $x=5;} function quiet(Other $n):int{return $n->x;}',
               'main': 'echo omitted(),supplied(),quiet(new Other());return 8;'}
    changed = base.replace('$v=2', '$v=4')
    return sources, [(None, '', b'395'), ('base', changed, b'595'),
                     ('base', changed.replace('$x=1', '$x=3'), b'7115'),
                     ('base', base.replace('public int', 'protected int'), 'protected'),
                     ('base', base, b'395')]


def prove(work, category, compiler, library):
    app, out = work/'app', work/'output'
    app.mkdir()
    source_edit(app/'module.json', '{}')
    sources, edits = {'properties': properties, 'methods': methods, 'constants': constants,
                      'construction': construction}[category]()
    for name, text in sources.items():
        source_edit(app/(name+'.phs'), text)
    edits.append((None, '', edits[-1][2]))
    with service(app, out) as resident:
        for i, (name, text, expected) in enumerate(edits):
            before = artifacts(out)
            if name:
                source_edit(app/(name+'.phs'), text)
            got = invoke(resident)
            clean = work/f'fresh-{i}'
            with service(app, clean) as fresh:
                reference = invoke(fresh)
                fresh.stdin.close()
            if isinstance(expected, str):
                assert expected.lower() in got.get('error', '').lower(), (i, got)
                assert got['error'] == reference.get('error') and artifacts(out) == before, (i, reference)
                continue
            assert 'error' not in got and 'error' not in reference, (i, got, reference)
            after = artifacts(out)
            assert after == artifacts(clean), (category, i, 'generated bytes differ')
            manifest = json.loads((out/'manifest.json').read_text())
            names = {unit: Path(path).stem for path, unit in manifest['sources'].items()}
            changed = incremental_native_build(out, work/'objects', compiler, library, expected,
                                               cxx_flags=('-stdlib=libc++',))
            def label(path):
                return names.get(str(path), str(path))
            emitted = {Path(path).stem for path in got['emitted_sources']}
            rebuilt = {label(p) for p in changed}
            delta = {p for p in before.keys() | after.keys() if before.get(p) != after.get(p)}
            cpp = {label(p) for p in delta if p.suffix == '.cpp'}
            headers = sum(p.suffix == '.hpp' for p in delta)
            print(category, i, 'prepared', got['preparation']['prepared'], 'emitted', sorted(emitted),
                  'C++', sorted(cpp), 'headers', headers, 'rebuilt', sorted(rebuilt), flush=True)
            if i:
                assert 'control' not in emitted | cpp | rebuilt, (category, i, emitted, cpp, rebuilt)
            if i and name:
                if category == 'properties':
                    assert cpp == {'reader'} and headers == 1
                    assert rebuilt == {'node', 'reader', 'writer', 'maker', 'main'}, rebuilt
                elif category == 'methods':
                    assert cpp == {'child'}
                    assert rebuilt == ({'child'} if i == 1 else {'child', 'main'}), rebuilt
                elif category == 'constants':
                    if name == 'left':
                        assert not (got['preparation']['prepared'] or cpp or headers or rebuilt)
                    elif name == 'right':
                        assert rebuilt == cpp == {'reader'}
                elif category == 'construction':
                    if i == 2:
                        assert not cpp and headers == 1
                        assert rebuilt == {'base', 'child', 'explicit', 'omitted'}
                    elif i == 1:
                        assert cpp == rebuilt == {'base', 'omitted'}
            if i == len(edits)-1:
                assert not (emitted or delta or rebuilt or got['preparation']['prepared'])
                incremental_native_build(clean, work/'clean-objects', compiler, library, expected,
                                         cxx_flags=('-stdlib=libc++',))
        resident.stdin.close()


if __name__ == '__main__':
    with tempfile.TemporaryDirectory(prefix='scpp-member-incremental-') as tmp:
        prove(Path(tmp), sys.argv[1], sys.argv[2], Path(sys.argv[3]))
