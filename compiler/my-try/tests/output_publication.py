#!/usr/bin/env python3
"""Output-file adapter and publication/recovery proofs through the shared runner."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import sys

APP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP / 'tools'))
from test_runner import CommandRunner, Task, run_tasks
from cpp_fixture import CppFixtureCompiler


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results', type=Path, required=True)
    args = parser.parse_args()
    output = args.results.resolve()
    output.mkdir(parents=True, exist_ok=False)
    expected = ''.join(hashlib.sha256(bytes(i % 256 for i in range(length))).hexdigest() + '\n'
                       for length in [0, 1, 3, 55, 56, 63, 64, 65, 127, 128, 10000, 131071, 131072, 131073]).encode()
    with CommandRunner(output / 'logs', APP.parents[1], jobs=12, journals=[output / 'commands.json']) as runner:
        executable = output / 'adapter'
        compiler = CppFixtureCompiler(runner, APP.parents[1], output, pch=False)
        compiler.compile('adapter-build', APP / 'tests/fixtures/output_files.cpp', executable)
        def check(name, command):
            root = output / name
            root.mkdir()
            outside = output / (name + '-outside')
            outside.write_text('untouched')
            (root / 'link').symlink_to(outside)
            os.mkfifo(root / 'pipe')
            (root / 'sub').mkdir()
            (root / 'sub/link').symlink_to(output, target_is_directory=True)
            observed = runner.run(name, [*command, root])
            if observed != expected or outside.read_text() != 'untouched':
                raise RuntimeError('Adapter bytes/digest/protection mismatch')
        run_tasks([Task('php-adapter', lambda: check('php-adapter', ['php', APP / 'tests/fixtures/output_files.php'])),
                   Task('native-adapter', lambda: check('native-adapter', [executable])),
                   Task('publication', lambda: runner.run('publication',
                       ['php', APP / 'tests/fixtures/output_publication.php', output / 'publication']))], jobs=12)

        def cli_publication():
            sources = output / 'cli-sources'
            sources.mkdir()
            (sources / 'main.phs').write_text('return answer();')
            library = sources / 'library.phs'
            library.write_text('function answer(): int { return 7; }')
            published = output / 'cli-published'
            command = ['php', APP / 'main.php', '--s2s', sources, '--no-prelower-templates', '--entry', 'main.phs', '--output', published]
            def invoke(name, expected=0):
                return runner.run(name, command, expected=expected, cli_reason='Tests disk publication CLI and process locking')
            invoke('cli-first')
            manifest_path = published / '.scpp-output.manifest'
            status_path = published / '.scpp-output.status'
            def snapshot():
                rows = json.loads(manifest_path.read_bytes())['files']
                return {p: ((published / p).read_bytes(), (published / p).stat().st_mtime_ns,
                            (published / p).stat().st_ino) for p in [r['path'] for r in rows] + [manifest_path.name]}
            before = snapshot()
            invoke('cli-noop')
            if snapshot() != before:
                raise RuntimeError('Restart/no-op replaced generated bytes/mtime/inode')
            ready = status_path.read_bytes()
            with (published / '.scpp-output.lock').open('rb') as lock:
                for mode in (fcntl.LOCK_SH, fcntl.LOCK_EX):
                    fcntl.flock(lock, mode)
                    invoke('cli-contention-' + str(mode), 1)
                    if status_path.read_bytes() != ready or snapshot() != before:
                        raise RuntimeError('Rejected concurrent writer changed output')
                    fcntl.flock(lock, fcntl.LOCK_UN)
            library.write_text('function answer(): int { return missing(); }')
            if invoke('cli-failure', 1):
                raise RuntimeError('Failed revision exposed a bundle')
            if not status_path.read_bytes().startswith(b'scpp-output-v1:pending:') or snapshot() != before:
                raise RuntimeError('Preparation failure published output or left ready marker')
            library.write_text('function answer(): int { return 9; }')
            invoke('cli-retry')
            after = snapshot()
            changed = [p for p in before if before[p] != after[p] and p != manifest_path.name]
            if len(changed) != 1 or not changed[0].startswith('units/'):
                raise RuntimeError('Body edit did not isolate owning translation unit: ' + repr(changed))
            manifest_bytes = manifest_path.read_bytes()
            if status_path.read_bytes() != b'scpp-output-v1:ready:' + hashlib.sha256(manifest_bytes).hexdigest().encode() + b'\n':
                raise RuntimeError('Ready marker does not match committed manifest')
            # Build directly from the published paths and manifest, never rematerialize.
            with (published / '.scpp-output.lock').open('rb') as lock:
                fcntl.flock(lock, fcntl.LOCK_SH)
                objects = []
                for index, row in enumerate(json.loads(manifest_bytes)['files']):
                    artifact = published / row['path']
                    if hashlib.sha256(artifact.read_bytes()).hexdigest() != row['sha256']:
                        raise RuntimeError('Published digest mismatch')
                    if row['kind'] == 'translation_unit':
                        obj = output / ('published-' + str(index) + '.o')
                        runner.run('published-unit-' + str(index), [*compiler.flags, '-I', published, '-c', artifact, '-o', obj])
                        objects.append(obj)
                program = output / 'published-program'
                runner.run('published-link', [*compiler.flags, *objects, '-o', program])
                runner.run('published-execute', [program], expected=9)
        run_tasks([Task('cli-publication', cli_publication)], jobs=12)

        def native_facade():
            repository = APP.parents[1]
            source = output / 'facade-source'
            source.mkdir()
            root = output / 'facade-output'
            fixture = (APP / 'tests/fixtures/output_facade.php').read_text()
            literal = "'" + str(root).replace('\\', '\\\\').replace("'", "\\'") + "'"
            (source / 'main.php').write_text(fixture + '\nOutput_Facade_Proof::run(' + literal + ');\n')
            project = output / 'facade-project'
            runner.run('facade-convert', ['php', repository / 'tools/php_portability/convert.php', source, project])
            runner.run('facade-framework', ['php', repository / 'tools/php_portability/install_native_runtime.php', project, '--filesystem'])
            cli = repository / 'bin/scpp.php'
            runner.run('facade-init', ['php', cli, 'init', '--php-profile=strict'], cwd=project)
            config_path = project / 'prism.json'
            config = json.loads(config_path.read_text())
            config['runtime']['modules'] = ['compiler', 'filesystem']
            config['build']['cxx'] = 'clang++'
            config_path.write_text(json.dumps(config, indent=2) + '\n')
            runner.run('facade-build', ['php', cli, 'build', '--no-stan', '--build-runtime'], cwd=project, timeout=300)
            actual = runner.run('facade-execute', [project / '.prism/build/main'])
            if actual != hashlib.sha256(b'abc\0def').hexdigest().encode():
                raise RuntimeError('Converted native facade result mismatch')
        run_tasks([Task('native-facade', native_facade)], jobs=12)
        (output / 'summary.json').write_text(json.dumps(dict(passed=True, native_adapter=True,
            publication_recovery=True, shared_and_exclusive_lock_contention=True, published_program_executed=True,
            converted_native_facade=True, stan=False,
            native_compiler_rebuilt=False), indent=2) + '\n')


if __name__ == '__main__':
    main()
